#!/usr/bin/env python3
"""Compare delivered DelPhi/PETIT binaries on byte-identical frozen inputs.

Run inside either architecture's container after checking input/source/image
hashes. Three fresh serial trials each execute two model/coarse/focus triplets;
focus reads the phi map generated by its own preceding coarse solve. PETIT uses
the identical saved energy table and seed on both architectures. No compiler
flags or executable are changed: the original x86 PGI binary remains baseline.
The native SLURM/SSH launchers supply project-backed output/temp directories.
"""
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import statistics
import subprocess
import time

from compare_hewl_pbmc import petit_input, populations


def digest(path):
    """Identify the exact binary/input rather than relying on its filename."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def solver_record(text):
    """Retain physical energy and actual final iteration/residual for comparison.

    A zero exit alone is insufficient; require the normal completion and finite
    energy. The residual is reported, not relabeled as a convergence success.
    """
    energy = re.findall(r"All required energy terms but grid and self_react\.:\s*([-+\d.eEdD]+)", text)
    assert len(energy) == 1 and "energy calculations done" in text
    value = float(energy[0].replace("D", "E").replace("d", "e"))
    assert math.isfinite(value)
    iterations = re.findall(r"([-+\d.EeDd]+)\s+([-+\d.EeDd]+)\s+at\s+(\d+)\s+iterations", text)
    assert iterations
    rms, maximum, count = iterations[-1]
    rms, maximum = [float(x.replace("D", "E").replace("d", "e")) for x in (rms, maximum)]
    assert math.isfinite(rms) and math.isfinite(maximum)
    return {"energy_kT": value, "last_reported_iterations": int(count),
            "last_reported_rms": rms, "last_reported_maximum": maximum,
            "requested_maxc": 0.0001, "requested_tolerance_met_at_last_report": maximum <= 0.0001}


def run(inputs, output):
    """Measure three cold-process repeats; exclude staging/audit from each timer."""
    # One physical execution context on both hosts; prohibit migration during
    # the serial component screen. Original affinity is preserved as evidence.
    original_affinity = sorted(os.sched_getaffinity(0))
    os.sched_setaffinity(0, {original_affinity[0]})
    protocol = json.loads((inputs / "protocol.json").read_text())
    for name, expected in protocol["file_sha256"].items():
        assert digest(inputs / name) == expected
    sites, _, _ = petit_input(inputs, 21)
    output.mkdir()
    binary = Path("/Delphi/delphi_pgf90")
    petit = Path("/programs/petit1.6.1/petit")
    metadata = {"architecture": os.uname().machine, "original_allowed_cpus": original_affinity,
                "allowed_cpus": sorted(os.sched_getaffinity(0)),
                "delphi_sha256": digest(binary), "petit_sha256": digest(petit),
                "input_protocol_sha256": digest(inputs / "protocol.json"),
                "limits": "Serial fixed-input component screen; not a compiler-only or ISA-only speed comparison."}
    (output / "provenance.json").write_text(json.dumps(metadata, indent=2) + "\n")
    rows = []
    env = dict(os.environ, OMP_NUM_THREADS="1")
    for repeat in (1, 2, 3):
        work = output / f"repeat-{repeat}"
        work.mkdir()
        for name in protocol["file_sha256"]:
            shutil.copyfile(inputs / name, work / name)
        for deck in protocol["decks_in_execution_order"]:
            name = Path(deck).stem
            with (work / (name + ".out")).open("w") as stdout:
                start = time.perf_counter()
                subprocess.run([str(binary), deck], cwd=work, env=env,
                               stdout=stdout, stderr=subprocess.STDOUT, check=True)
                elapsed = time.perf_counter() - start
            record = solver_record((work / (name + ".out")).read_text())
            record.update(component="delphi", deck=deck, repeat=repeat, wall_seconds=elapsed)
            rows.append(record)
        with (work / "PBMC.dat").open() as stdin, (work / "petit.out").open("w") as stdout, (work / "petit.err").open("w") as stderr:
            start = time.perf_counter()
            subprocess.run([str(petit), "-H", "6,6,1", "-E", "0,0,1", "-T", "310", "-c", "2",
                            "-r", "1729", "-q", "1000", "100000"], cwd=work, env=env,
                           stdin=stdin, stdout=stdout, stderr=stderr, check=True)
            elapsed = time.perf_counter() - start
        means, final = populations(work / "petit.out", sites)
        rows.append({"component": "petit", "repeat": repeat, "wall_seconds": elapsed,
                     "means": means, "final_states": final})
        (output / "observations.json").write_text(json.dumps(rows, indent=2) + "\n")
    summary = []
    for deck in protocol["decks_in_execution_order"]:
        group = [row for row in rows if row.get("deck") == deck]
        assert len(group) == 3
        assert len({row["energy_kT"] for row in group}) == 1, "Unexpected within-architecture deterministic variation"
        summary.append({"component": "delphi", "deck": deck,
                        "median_wall_seconds": statistics.median(row["wall_seconds"] for row in group),
                        "min_wall_seconds": min(row["wall_seconds"] for row in group),
                        "max_wall_seconds": max(row["wall_seconds"] for row in group),
                        "numerical_record": {key: group[0][key] for key in ["energy_kT", "last_reported_iterations", "last_reported_rms", "last_reported_maximum", "requested_tolerance_met_at_last_report"]}})
    mc = [row for row in rows if row["component"] == "petit"]
    assert len(mc) == 3 and all(row["means"] == mc[0]["means"] and row["final_states"] == mc[0]["final_states"] for row in mc)
    summary.append({"component": "petit", "median_wall_seconds": statistics.median(row["wall_seconds"] for row in mc),
                    "min_wall_seconds": min(row["wall_seconds"] for row in mc), "max_wall_seconds": max(row["wall_seconds"] for row in mc)})
    (output / "summary.json").write_text(json.dumps({"passed": True, "components": summary}, indent=2) + "\n")


def audit_shell(inputs, output):
    """Independently audit the identical Bash launcher used in both containers.

    This path supports the historical x86 image without injecting a Python
    runtime into it. GNU date overhead is retained identically on both hosts;
    residuals and iterations accompany every speed observation.
    """
    protocol = json.loads((inputs / "protocol.json").read_text())
    for name, expected in protocol["file_sha256"].items():
        assert digest(inputs / name) == expected
    sites, _, _ = petit_input(inputs, 21)
    rows = []
    seen = set()
    for line in (output / "timings.tsv").read_text().splitlines():
        component, repeat, name, nanoseconds = line.split("\t")
        repeat = int(repeat)
        assert repeat in (1, 2, 3) and int(nanoseconds) > 0
        key = component, repeat, name
        assert key not in seen
        seen.add(key)
        work = output / f"repeat-{repeat}"
        for filename, expected in protocol["file_sha256"].items():
            assert digest(work / filename) == expected
        row = {"component": component, "repeat": repeat, "input": name,
               "wall_seconds": int(nanoseconds) / 1e9}
        if component == "delphi":
            assert name in protocol["decks_in_execution_order"]
            row.update(solver_record((work / (Path(name).stem + ".out")).read_text()))
        else:
            assert component == "petit" and name == "PBMC.dat"
            means, final = populations(work / "petit.out", sites)
            row.update(means=means, final_states=final)
        rows.append(row)
    expected = {("delphi", repeat, deck) for repeat in (1, 2, 3) for deck in protocol["decks_in_execution_order"]}
    expected.update(("petit", repeat, "PBMC.dat") for repeat in (1, 2, 3))
    assert seen == expected
    groups = []
    for component, name in [("delphi", deck) for deck in protocol["decks_in_execution_order"]] + [("petit", "PBMC.dat")]:
        group = [row for row in rows if row["component"] == component and row["input"] == name]
        assert len(group) == 3
        if component == "delphi":
            assert len({row["energy_kT"] for row in group}) == 1
        else:
            assert all(row["means"] == group[0]["means"] and row["final_states"] == group[0]["final_states"] for row in group)
        groups.append({"component": component, "input": name,
                       "median_wall_seconds": statistics.median(row["wall_seconds"] for row in group),
                       "min_wall_seconds": min(row["wall_seconds"] for row in group),
                       "max_wall_seconds": max(row["wall_seconds"] for row in group)})
    (output / "observations.json").write_text(json.dumps(rows, indent=2) + "\n")
    (output / "summary.json").write_text(json.dumps({"passed": True, "components": groups,
        "input_protocol_sha256": digest(inputs / "protocol.json"),
        "limits": "Same Bash/date launcher in both containers; three serial samples/deck. Hardware, compiler and libraries differ; not ISA-only attribution. Requested PB tolerance is not always reached."}, indent=2) + "\n")


def main():
    """Accept only explicit read-only input and fresh output directories."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--audit-shell", action="store_true")
    args = parser.parse_args()
    if args.audit_shell:
        audit_shell(args.inputs.resolve(), args.output.resolve())
    else:
        run(args.inputs.resolve(), args.output.resolve())


if __name__ == "__main__":
    main()
