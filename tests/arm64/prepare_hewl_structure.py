#!/usr/bin/env python3
"""Prepare the pinned 4LZT protein input before force-field/topology generation.

Resolve residue-level alternate locations, omit crystal heteroatoms/ANISOU and
write a protein-only PDB plus audit JSON. Preserve residue numbering and the four
declared disulfides. No CpHMD renaming, topology, MD or job submission occurs;
the next stage uses the container's pdb2cphmd/pdb2gmx tools and verifies its
topology/site list before solvation and scientific validation.
"""
import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path

SOURCE_SHA256 = 'eec47d81860d9da162f3f8151126af361aba4d4c8055f686dd4cae9d29991941'
DISULFIDES = [(6, 127), (30, 115), (64, 80), (76, 94)]
# Canonical heavy atoms provide a force-field-independent completeness check.
# Terminal OXT is optional here; pdb2gmx constructs the selected terminal group.
SIDECHAINS = {
    'ALA': 'CB', 'ARG': 'CB CG CD NE CZ NH1 NH2', 'ASN': 'CB CG OD1 ND2',
    'ASP': 'CB CG OD1 OD2', 'CYS': 'CB SG', 'GLN': 'CB CG CD OE1 NE2',
    'GLU': 'CB CG CD OE1 OE2', 'GLY': '', 'HIS': 'CB CG ND1 CD2 CE1 NE2',
    'ILE': 'CB CG1 CG2 CD1', 'LEU': 'CB CG CD1 CD2', 'LYS': 'CB CG CD CE NZ',
    'MET': 'CB CG SD CE', 'PHE': 'CB CG CD1 CD2 CE1 CE2 CZ', 'PRO': 'CB CG CD',
    'SER': 'CB OG', 'THR': 'CB OG1 CG2', 'TRP': 'CB CG CD1 CD2 NE1 CE2 CE3 CZ2 CZ3 CH2',
    'TYR': 'CB CG CD1 CD2 CE1 CE2 CZ OH', 'VAL': 'CB CG1 CG2',
}


def residue_key(line):
    """Identify a deposited residue without conflating chain/insertion codes."""
    return line[21], int(line[22:26]), line[26], line[17:20]


def atom_signature(line):
    """Compare structural identity with old inputs independent of record layout."""
    return (residue_key(line), line[12:16].strip(), line[16],
            tuple(float(line[i:i + 8]) for i in (30, 38, 46)))


def clean_protein(lines):
    """Select one coherent alternate label per residue and validate the protein.

    Keep shared blank-label atoms plus the label with highest mean occupancy;
    break ties in favor of A, then alphabetical order. Never pick each atom's
    alternate independently, which could produce a mixed residue conformation.
    Check full heavy-atom coverage, unique names and expected HEWL cysteines.
    """
    residues = defaultdict(list)
    for line in lines:
        if line.startswith('ATOM  '):
            residues[residue_key(line)].append(line)
    if {(chain, number, insertion) for chain, number, insertion, _ in residues} != {
            ('A', number, ' ') for number in range(1, 130)} or len(residues) != 129:
        raise ValueError('Expected exactly chain A residues 1–129 without insertions')
    selected, choices, inventory = [], [], []
    for key, atoms in residues.items():
        labels = defaultdict(list)
        for line in atoms:
            if line[16] != ' ':
                labels[line[16]].append(float(line[54:60]))
        means = {label: sum(values) / len(values) for label, values in labels.items()}
        chosen = sorted(means, key=lambda label: (-means[label], label != 'A', label))[0] if means else None
        kept = [line[:16] + ' ' + line[17:] for line in atoms
                if line[16] == ' ' or line[16] == chosen]
        # Deposited hydrogen positions are regenerated by pdb2gmx -ignh.
        kept = [line for line in kept if line[76:78].strip() not in ('H', 'D')]
        names = [line[12:16].strip() for line in kept]
        if len(names) != len(set(names)):
            raise ValueError('Duplicate atoms after alternate selection: ' + str(key))
        required = set(('N CA C O ' + SIDECHAINS[key[3]]).split())
        if not required.issubset(names):
            raise ValueError('Missing heavy atoms for {}: {}'.format(key, sorted(required - set(names))))
        if means:
            choices.append({'residue': list(key), 'mean_occupancy': means, 'selected': chosen})
        inventory.append({'chain': key[0], 'residue_number': key[1], 'residue_name': key[3]})
        selected.extend(kept)
    cysteines = sorted(item['residue_number'] for item in inventory if item['residue_name'] == 'CYS')
    if cysteines != sorted(number for pair in DISULFIDES for number in pair):
        raise ValueError('Cysteine inventory differs from the four expected disulfides')
    return selected, choices, inventory


def main():
    """Pin the source, create new preparation outputs and record every choice."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--previous-pdb', type=Path, help='Optional read-only mini05 input comparison')
    args = parser.parse_args()
    digest = hashlib.sha256(args.source.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        parser.error('Source differs from the pinned official 4LZT PDB')
    if args.output_dir.exists():
        parser.error('Refusing to overwrite existing preparation outputs')
    lines = args.source.read_text().splitlines()
    selected, choices, inventory = clean_protein(lines)
    declared = [line for line in lines if line.startswith('SSBOND')]
    declared_pairs = sorted((int(line[17:21]), int(line[31:35])) for line in declared)
    if declared_pairs != sorted(DISULFIDES):
        raise ValueError('Deposited disulfides differ from the expected HEWL pairs')
    report = {
        'pdb_id': '4LZT', 'source_url': 'https://files.rcsb.org/download/4LZT.pdb',
        'source_sha256': digest, 'input_atom_records': sum(line.startswith('ATOM  ') for line in lines),
        'protein_heavy_atoms_selected': len(selected), 'residues': inventory,
        'alternate_location_choices': choices, 'disulfide_pairs': DISULFIDES,
        'discarded_heteroatom_residues': dict(Counter(line[17:20] for line in lines if line.startswith('HETATM'))),
        'heteroatom_count_units': 'atom records, not molecule counts',
        'pending': ['CpHMD residue/terminal mapping', 'topology and disulfide verification',
                    'solvation/ions and minimization/equilibration', 'PB/MC and cycle/restart validation'],
    }
    if args.previous_pdb:
        previous = args.previous_pdb.read_bytes()
        report['previous_pdb_sha256'] = hashlib.sha256(previous).hexdigest()
        report['previous_atom_coordinates_match_source'] = Counter(
            atom_signature(line) for line in previous.decode().splitlines() if line.startswith('ATOM  ')) == Counter(
            atom_signature(line) for line in lines if line.startswith('ATOM  '))
    args.output_dir.mkdir(parents=True)
    output = args.output_dir / '4LZT-protein.pdb'
    # Preserve deposited disulfide declarations; omit crystal box/heteroatoms.
    output.write_text('\n'.join(['REMARK 900 PROTEIN INPUT FROM PINNED 4LZT; SEE structure-audit.json']
                                + declared + selected + ['TER', 'END']) + '\n')
    report['cleaned_pdb_sha256'] = hashlib.sha256(output.read_bytes()).hexdigest()
    (args.output_dir / 'structure-audit.json').write_text(json.dumps(report, indent=2) + '\n')
    print('Prepared {} heavy atoms in 129 residues; four disulfides preserved'.format(len(selected)))
    print('Topology generation and scientific validation have not run.')


if __name__ == '__main__':
    main()
